"""Validated immutable waypoint poses for the LEAP ball state-cycle task."""

from __future__ import annotations

from dataclasses import dataclass
from types import MappingProxyType
from typing import Mapping

import numpy as np


@dataclass(frozen=True)
class PoseWaypoint:
    """One recorded hand/object waypoint and its actuator target."""

    name: str
    qpos: np.ndarray
    hand_qpos: np.ndarray
    ball_pos: np.ndarray
    ball_quat: np.ndarray
    ctrl: np.ndarray


def _readonly(values: np.ndarray) -> np.ndarray:
    result = np.asarray(values, dtype=np.float64).copy()
    result.setflags(write=False)
    return result


def make_pose_waypoint(name: str, qpos: np.ndarray, ctrl: np.ndarray) -> PoseWaypoint:
    """Validate and freeze one waypoint at module-load time."""
    qpos_array = np.asarray(qpos, dtype=np.float64)
    ctrl_array = np.asarray(ctrl, dtype=np.float64)
    if qpos_array.shape != (23,):
        raise ValueError(f"{name} qpos must have shape (23,), got {qpos_array.shape}")
    if ctrl_array.shape != (16,):
        raise ValueError(f"{name} ctrl must have shape (16,), got {ctrl_array.shape}")
    if not np.isfinite(qpos_array).all() or not np.isfinite(ctrl_array).all():
        raise ValueError(f"{name} waypoint values must all be finite")

    normalized_qpos = qpos_array.copy()
    quat_norm = float(np.linalg.norm(normalized_qpos[19:23]))
    if not np.isfinite(quat_norm) or quat_norm <= 1e-12:
        raise ValueError(f"{name} ball quaternion must have non-zero finite norm")
    normalized_qpos[19:23] /= quat_norm
    frozen_qpos = _readonly(normalized_qpos)
    return PoseWaypoint(
        name=name,
        qpos=frozen_qpos,
        hand_qpos=_readonly(frozen_qpos[:16]),
        ball_pos=_readonly(frozen_qpos[16:19]),
        ball_quat=_readonly(frozen_qpos[19:23]),
        ctrl=_readonly(ctrl_array),
    )


